console.log("--- ⚖️ SENTENCIAS DEL TRIBUNAL ESTRIDOR (`===`) ---");

console.log(5 === 5);            
console.log(5 === "5");          
console.log(0 === false);        
console.log(null === undefined); 


console.log("\n--- ⚠️ ADVERTENCIAS DE LA IGUALDAD DÉBIL (`==`) ---");

console.log(5 == "5");           
console.log(0 == false);         
console.log("" == false);        


console.log(null == undefined);  


console.log("\n--- 🗡️ EL VERDICTO DE LA DESIGUALDAD (`!==` vs `!=`) ---");

console.log(5 !== "5");          
console.log(5 !== 5);            


console.log(5 != "5");